"""Write the poster's cost bar chart as a PGFPlots fragment.

Reads cost_usd_per_pass for each config from data/coding/costs.json and
writes poster/figures/cost-bars.tex. Standard library only.
"""

import json
import math
from pathlib import Path
from typing import Dict, List

REPO = Path(__file__).resolve().parent.parent
COSTS = REPO / "data" / "coding" / "costs.json"
OUT = REPO / "poster" / "figures" / "cost-bars.tex"

# (costs.json config key, x-axis label as it appears in the TeX source)
CATEGORIES = [
    ("haiku:low", "Haiku\\,low"),
    ("sonnet:low", "Sonnet\\,low"),
    ("sonnet:medium", "Sonnet\\,medium"),
    ("sonnet:high", "Sonnet\\,high"),
    ("sonnet:xhigh", "Sonnet\\,xhigh"),
]

# (costs.json set key, legend text, fill, draw)
SERIES = [
    ("easy", "Easy set (1 trial)", "gray!60", "gray!80!black"),
    ("hard", "Hard set (3 trials)", "blue!55!black", "blue!75!black"),
]


def load_values(path: Path) -> Dict[str, Dict[str, float]]:
    """Return {set: {config: cost_usd_per_pass}} for every entry in the file."""
    with path.open(encoding="utf-8") as fh:
        rows = json.load(fh)
    values: Dict[str, Dict[str, float]] = {}
    for row in rows.values():
        values.setdefault(row["set"], {})[row["config"]] = float(row["cost_usd_per_pass"])
    return values


def build_tex(values: Dict[str, Dict[str, float]]) -> str:
    peak = 0.0
    for set_key, _, _, _ in SERIES:
        for config, _ in CATEGORIES:
            try:
                peak = max(peak, values[set_key][config])
            except KeyError as exc:
                raise KeyError(f"missing {set_key}|{config} in {COSTS}") from exc
    ymax = math.ceil(1.2 * peak * 100) / 100

    lines: List[str] = [
        "% Grouped bars: dollars per success by config, easy vs hard set.",
        "% Generated by analysis/make_poster_figures.py from data/coding/costs.json.",
        "\\begin{tikzpicture}",
        "\\begin{axis}[",
        "    width=0.92\\linewidth,",
        "    height=6cm,",
        "    ybar,",
        "    bar width=8pt,",
        f"    ymin=0, ymax={ymax:.2f},",
        "    enlarge x limits=0.12,",
        "    ylabel={Dollars per success},",
        "    symbolic x coords={" + ", ".join(label for _, label in CATEGORIES) + "},",
        "    xtick=data,",
        "    x tick label style={font=\\footnotesize, rotate=18, anchor=east},",
        "    tick label style={font=\\footnotesize},",
        "    label style={font=\\small},",
        "    nodes near coords={\\$\\pgfmathprintnumber[fixed,fixed zerofill,precision=3]{\\pgfplotspointmeta}},",
        "    point meta=rawy,",
        "    nodes near coords style={font=\\scriptsize, rotate=90, anchor=west},",
        "    legend pos=north west,",
        "    legend style={font=\\small,fill=white,fill opacity=0.9,text opacity=1,draw=black!40},",
        "    grid=major,",
        "    grid style={dashed,gray!20},",
        "  ]",
        "",
    ]
    for set_key, legend, fill, draw in SERIES:
        lines.append(f"  \\addplot[fill={fill}, draw={draw}] coordinates {{")
        for config, label in CATEGORIES:
            lines.append(f"    ({label}, {values[set_key][config]})")
        lines.append("  };")
        lines.append(f"  \\addlegendentry{{{legend}}}")
        lines.append("")
    lines.append("\\end{axis}")
    lines.append("\\end{tikzpicture}")
    return "\n".join(lines) + "\n"


def main() -> None:
    values = load_values(COSTS)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build_tex(values), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
