def cost_rows(set_name: str) -> List[Tuple[Config, Dict[str, Any]]]:
    rows: List[Tuple[Config, Dict[str, Any]]] = []
    for entry in load_json(COSTS_PATH).values():
        if entry["set"] != set_name:
            continue
        model, effort = entry["config"].split(":")
        rows.append(((model_key(model), effort), entry))
    rows.sort(key=lambda item: sort_key(item[0]))
    return rows


def easy_cost_tex() -> str:
    rows = cost_rows("easy")
    n = len(rows)
    values = [entry["cost_usd_per_pass"] for _, entry in rows]
    xmin, xmax, ticks = log_bounds(values)
    xtick, xticklabels = dollar_ticks(ticks)
    positions = {config: n - i for i, (config, _) in enumerate(rows)}
    names = [config_name(config) for config, _ in rows]

    options = [
        *BASE_OPTIONS,
        "xbar",
        "xmode=log",
        "log origin=infty",
        f"xmin={xmin:g}",
        f"xmax={xmax:g}",
        "xlabel={Cost per success (\\$, log scale)}",
        f"xtick={xtick}",
        f"xticklabels={xticklabels}",
        f"ytick={brace_list([str(positions[c]) for c, _ in rows])}",
        f"yticklabels={brace_list(names)}",
        "ymin=0.4",
        f"ymax={n + 0.6}",
        "bar width=7pt",
        # On a log axis the bar coordinate is the logarithm; label with the raw dollar value instead.
        "point meta=rawx",
        "nodes near coords={\\$\\pgfmathprintnumber[fixed,precision=3]{\\pgfplotspointmeta}}",
        "every node near coord/.append style={font=\\scriptsize}",
    ]
    plots: List[str] = []
    for model in MODELS:
        pts = " ".join(
            f"({entry['cost_usd_per_pass']:.4f},{positions[config]})"
            for config, entry in rows
            if config[0] == model
        )
        if pts:
            plots.append(
                f"\\addplot[fill={FILL_COLOR[model]}, draw={LINE_COLOR[model]}, bar shift=0pt] "
                f"coordinates {{{pts}}};"
            )
    return axis_tex(options, plots)


def effort_cost_tex() -> str:
    rows = cost_rows("easy")
    values = [entry["cost_usd_per_pass"] for _, entry in rows]
    ymin, ymax, ticks = log_bounds(values)
    ytick, yticklabels = dollar_ticks(ticks)
    xtick = brace_list([str(i) for i in range(1, len(EFFORTS) + 1)])
    xticklabels = brace_list(list(EFFORTS))

    options = [
        *BASE_OPTIONS,
        f"xtick={xtick}",
        f"xticklabels={xticklabels}",
        "xmin=0.6",
        f"xmax={len(EFFORTS) + 0.4}",
        "xlabel={Effort level}",
        "ymode=log",
        f"ymin={ymin:g}",
        f"ymax={ymax:g}",
        f"ytick={ytick}",
        f"yticklabels={yticklabels}",
        "ylabel={Cost per success (\\$, log scale)}",
        "legend pos=south east",
        "typeset ticklabels with strut",  # keeps "max" on the same baseline as the other labels
    ]
    markers = {"haiku": "*", "sonnet": "square*"}
    plots: List[str] = []
    for model in MODELS:
        pts = " ".join(
            f"({EFFORTS.index(config[1]) + 1},{entry['cost_usd_per_pass']:.4f})"
            for config, entry in rows
            if config[0] == model
        )
        if not pts:
            continue
        plots.append(
            f"\\addplot[color={LINE_COLOR[model]}, mark={markers[model]}, thick] "
            f"coordinates {{{pts}}};"
        )
        plots.append(f"\\addlegendentry{{{MODEL_LABEL[model]}}}")
    return axis_tex(options, plots)


