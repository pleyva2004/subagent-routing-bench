r"""Write the five pgfplots figures that the paper's figure environments \input.

Reads (never writes):
  experiments/01-reasoning-ladder/results.jsonl, tasks.json, tasks2.json
  data/coding/costs.json

Writes, overwriting (each file holds one tikzpicture, no figure environment):
  paper/figures/reasoning-trace.tex
  paper/figures/easy-cost.tex
  paper/figures/effort-cost.tex
  paper/figures/hard-pass.tex
  paper/figures/hard-cost-time.tex

Run from anywhere:
  python3 analysis/make_tikz_figures.py
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any, Dict, List, Sequence, Set, Tuple

ROOT = Path(__file__).resolve().parents[1]
LADDER_DIR = ROOT / "experiments" / "01-reasoning-ladder"
RESULTS_PATH = LADDER_DIR / "results.jsonl"
TASK_PATHS = (LADDER_DIR / "tasks.json", LADDER_DIR / "tasks2.json")
COSTS_PATH = ROOT / "data" / "coding" / "costs.json"
OUT_DIR = ROOT / "paper" / "figures"

MODELS = ("haiku", "sonnet")
MODEL_LABEL = {"haiku": "Haiku", "sonnet": "Sonnet"}
LADDER_EFFORTS = ("low", "medium", "high", "xhigh")
EFFORTS = ("low", "medium", "high", "xhigh", "max")

# Sonnet is blue. Haiku is gray; its fills are lightened so they read against the blue.
LINE_COLOR = {"haiku": "arxivgray", "sonnet": "arxivblue"}
FILL_COLOR = {"haiku": "arxivgray!60", "sonnet": "arxivblue"}

HEADER = "% Generated by analysis/make_tikz_figures.py. Edit the script, not this file.\n"

BASE_OPTIONS = [
    "width=0.88\\linewidth",
    "height=7cm",
    "grid=major",
    "grid style={dashed, gray!30}",
    "tick label style={font=\\small}",
    "label style={font=\\small}",
]

Config = Tuple[str, str]  # (model key, effort level)


def load_json(path: Path) -> Any:
    with path.open(encoding="utf-8") as handle:
        return json.load(handle)


def load_jsonl(path: Path) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                rows.append(json.loads(line))
    return rows


def model_key(raw: str) -> str:
    """Map 'claude-haiku-5-5' or 'haiku' to 'haiku'; same for sonnet."""
    for key in MODELS:
        if key in raw:
            return key
    raise ValueError(f"unknown model {raw!r}")


def config_name(config: Config) -> str:
    return f"{MODEL_LABEL[config[0]]} {config[1]}"


def sort_key(config: Config) -> Tuple[int, int]:
    return (MODELS.index(config[0]), EFFORTS.index(config[1]))


def brace_list(items: Sequence[str]) -> str:
    return "{" + ",".join(items) + "}"


def axis_tex(options: Sequence[str], plots: Sequence[str]) -> str:
    lines = [
        HEADER.rstrip("\n"),
        "\\begin{tikzpicture}",
        "\\begin{axis}[",
        *[f"  {option}," for option in options],
        "]",
        *plots,
        "\\end{axis}",
        "\\end{tikzpicture}",
        "",
    ]
    return "\n".join(lines)


def log_bounds(values: Sequence[float]) -> Tuple[float, float, List[float]]:
    """Decade-aligned limits and tick values that cover the data on a log axis."""
    low = math.floor(math.log10(min(values)))
    high = math.ceil(math.log10(max(values)))
    ticks = [10.0 ** k for k in range(low, high + 1)]
    return 10.0 ** low, 10.0 ** high, ticks


def dollar_ticks(ticks: Sequence[float]) -> Tuple[str, str]:
    positions = brace_list([f"{t:g}" for t in ticks])
    labels = brace_list(["\\$" + f"{t:g}" for t in ticks])
    return positions, labels


