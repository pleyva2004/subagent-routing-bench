def hard_pass_tex() -> str:
    rows = cost_rows("hard")
    names = [config_name(config) for config, _ in rows]
    positions = list(range(1, len(rows) + 1))

    options = [
        *BASE_OPTIONS,
        "xmin=0.4",
        f"xmax={len(rows) + 0.6}",
        f"xtick={brace_list([str(p) for p in positions])}",
        f"xticklabels={brace_list(names)}",
        "x tick label style={font=\\scriptsize}",
        "ymin=0.5",
        "ymax=1.0",
        "ytick={0.5,0.6,0.7,0.8,0.9,1.0}",
        "ylabel={Pass rate (passes/runs)}",
        "legend pos=south west",
    ]
    plots: List[str] = []
    for model in MODELS:
        lines = ["x,y,eplus,eminus"]
        for index, (config, entry) in zip(positions, rows):
            if config[0] != model:
                continue
            rate = int(entry["passes"]) / int(entry["runs"])
            low, high = entry["pass_rate_95ci"]
            lines.append(
                f"{index},{rate:.4f},{max(high - rate, 0.0):.4f},{max(rate - low, 0.0):.4f}"
            )
        if len(lines) == 1:
            continue
        plots.append(
            f"\\addplot[only marks, mark=*, color={LINE_COLOR[model]}, "
            f"error bars/.cd, y dir=both, y explicit] "
            f"table[col sep=comma, x=x, y=y, y error plus=eplus, y error minus=eminus] {{"
        )
        plots.extend(lines)
        plots.append("};")
        plots.append(f"\\addlegendentry{{{MODEL_LABEL[model]}}}")
    return axis_tex(options, plots)


def hard_cost_time_tex() -> str:
    rows = cost_rows("hard")
    xs = [float(entry["agent_seconds_per_run"]) for _, entry in rows]
    ys = [float(entry["cost_usd_per_pass"]) for _, entry in rows]

    options = [
        *BASE_OPTIONS,
        "xmin=0",
        f"xmax={max(xs) * 1.25:.1f}",
        "ymin=0",
        f"ymax={max(ys) * 1.25:.3f}",
        "xlabel={Agent seconds per run}",
        "ylabel={Cost per success (\\$)}",
        "legend pos=north west",
    ]
    # Sonnet low and medium sit close together, so each label gets its own side of the point.
    label_anchor = {("sonnet", "low"): "east", ("sonnet", "medium"): "south", ("sonnet", "xhigh"): "east"}
    plots: List[str] = []
    for model in MODELS:
        lines = ["x,y,label,anchor"]
        for config, entry in rows:
            if config[0] != model:
                continue
            lines.append(
                f"{float(entry['agent_seconds_per_run']):.1f},"
                f"{float(entry['cost_usd_per_pass']):.4f},{config_name(config)},"
                f"{label_anchor.get(config, 'west')}"
            )
        if len(lines) == 1:
            continue
        plots.append(
            f"\\addplot[only marks, mark=*, color={LINE_COLOR[model]}, "
            f"nodes near coords, point meta=explicit symbolic, "
            f"visualization depends on={{value \\thisrow{{anchor}} \\as \\labelanchor}}, "
            f"every node near coord/.append style={{anchor=\\labelanchor, font=\\scriptsize}}] "
            f"table[col sep=comma, x=x, y=y, meta=label] {{"
        )
        plots.extend(lines)
        plots.append("};")
        plots.append(f"\\addlegendentry{{{MODEL_LABEL[model]}}}")
    return axis_tex(options, plots)


# ---------------------------------------------------------------------------


def write_figure(name: str, text: str) -> Path:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / name
    path.write_text(text, encoding="utf-8")
    return path


def main() -> None:
    params = trace_params()
    outcomes = ladder_outcomes(params)
    trace_text, measures = reasoning_trace_tex(params, outcomes)

    written = [
        write_figure("reasoning-trace.tex", trace_text),
        write_figure("easy-cost.tex", easy_cost_tex()),
        write_figure("effort-cost.tex", effort_cost_tex()),
        write_figure("hard-pass.tex", hard_pass_tex()),
        write_figure("hard-cost-time.tex", hard_cost_time_tex()),
    ]

    print("Figure 1 (reasoning-trace), values in statements:")
    print(f"  {'config':<16}{'before 1st non-pass':>20}{'longest solved':>16}")
    for name, before, longest in measures:
        print(f"  {name:<16}{before:>20}{longest:>16}")
    print("Wrote:")
    for path in written:
        print(f"  {path}")


if __name__ == "__main__":
    main()
