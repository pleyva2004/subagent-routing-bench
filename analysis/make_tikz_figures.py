def trace_params() -> Dict[int, int]:
    """Trace level -> number of statements, from both task files."""
    params: Dict[int, int] = {}
    for path in TASK_PATHS:
        for task in load_json(path):
            if task["family"] != "trace":
                continue
            level, param = int(task["level"]), int(task["param"])
            if params.get(level, param) != param:
                raise ValueError(f"trace level {level} has two different params")
            params[level] = param
    return params


def ladder_outcomes(params: Dict[int, int]) -> Dict[Config, Dict[int, bool]]:
    """Map each config and trace level to solved or not. Solved means every run passed."""
    seen: Dict[Tuple[Config, int], Set[str]] = {}
    for row in load_jsonl(RESULTS_PATH):
        if row.get("family") != "trace":
            continue
        level = int(row["level"])
        if level not in params:
            raise ValueError(f"results name trace level {level}, which the task files lack")
        config = (model_key(row["model"]), row["effort"])
        seen.setdefault((config, level), set()).add(row["status"])

    outcomes: Dict[Config, Dict[int, bool]] = {}
    for (config, level), statuses in seen.items():
        if len(statuses) > 1:
            print(f"warning: {config_name(config)} trace level {level} has statuses {sorted(statuses)}")
        outcomes.setdefault(config, {})[level] = statuses == {"pass"}
    return outcomes


def ladder_measures(params: Dict[int, int], passed: Dict[int, bool]) -> Tuple[int, int]:
    """Return (longest trace solved before the first non-pass level, longest solved at all)."""
    before_first_fail = 0
    longest_solved = 0
    prefix_open = True
    for level in sorted(params):
        if passed.get(level, False):
            longest_solved = max(longest_solved, params[level])
            if prefix_open:
                before_first_fail = params[level]
        else:
            prefix_open = False
    return before_first_fail, longest_solved


def reasoning_trace_tex(
    params: Dict[int, int], outcomes: Dict[Config, Dict[int, bool]]
) -> Tuple[str, List[Tuple[str, int, int]]]:
    configs = [(model, effort) for model in MODELS for effort in LADDER_EFFORTS]
    measures: List[Tuple[str, int, int]] = []
    for config in configs:
        before, longest = ladder_measures(params, outcomes.get(config, {}))
        measures.append((config_name(config), before, longest))

    n = len(configs)
    positions = [n - i for i in range(n)]  # first config at the top
    names = [name for name, _, _ in measures]
    before_pts = " ".join(f"({before},{y})" for (_, before, _), y in zip(measures, positions))
    longest_pts = " ".join(f"({longest},{y})" for (_, _, longest), y in zip(measures, positions))

    options = [
        *BASE_OPTIONS,
        "xbar",
        "bar width=5pt",
        "xmin=0",
        f"xmax={max(m[2] for m in measures) * 1.15:.0f}",  # room for the value labels on the longest bars
        "xtick distance=200",
        "xlabel={Longest trace solved (statements)}",
        f"ytick={brace_list([str(p) for p in positions])}",
        f"yticklabels={brace_list(names)}",
        "ymin=0.4",
        f"ymax={n + 0.6}",
        "nodes near coords",
        "every node near coord/.append style={font=\\scriptsize}",
        # The top rows (Haiku) have short bars, so the top-right corner is empty.
        "legend style={at={(0.98,0.97)}, anchor=north east, font=\\small}",
    ]
    # Neutral shades: elsewhere blue means Sonnet and gray means Haiku, and these bars are measures, not models.
    plots = [
        "\\addplot[fill=black!70, draw=black!80, bar shift=-3pt] "
        f"coordinates {{{before_pts}}};",
        "\\addlegendentry{Before first failure}",
        "\\addplot[fill=black!20, draw=black!45, bar shift=3pt] "
        f"coordinates {{{longest_pts}}};",
        "\\addlegendentry{Longest solved at all}",
    ]
    return axis_tex(options, plots), measures


